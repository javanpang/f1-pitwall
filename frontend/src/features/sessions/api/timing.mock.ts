import type { SectorTime, TimeStatus, TimingRow, TyreCompound } from "../types";

const t = (
  seconds: number | null,
  status: TimeStatus = "no-time",
): SectorTime => ({
  seconds,
  status,
});

function row(
  position: number,
  driverAcronym: string,
  driverNumber: number,
  teamName: string,
  teamColour: string,
  intervalSeconds: number | null,
  sectors: [SectorTime, SectorTime, SectorTime],
  last: SectorTime,
  best: SectorTime,
  compound: TyreCompound,
  ageLaps: number | null,
  pitStops: number,
  positionChange: TimingRow["positionChange"] = "none",
): TimingRow {
  return {
    position,
    driverNumber,
    driverAcronym,
    teamName,
    teamColour,
    positionChange,
    intervalSeconds,
    sectors,
    lastLap: last,
    bestLap: best,
    tyre: { compound, ageLaps },
    pitStops,
  };
}

